const recipes = [];
function recipe(group, title, route, totals, tables, note = '') {
  recipes.push({group, title, route, totals, tables, note});
}
function grid(title, headings, rows) { return {title, headings, rows}; }
function across(head, cols, fields, title = 'Материалы') {
  return grid(title, ['Ресурс', ...fields.map(f => f[0])], [...cols].map(c =>
    [cells[c + head], ...fields.map(f => c + f[1])]));
}
function materials(head, cols, need, have, cost) {
  const table = across(head, cols, [['Нужно', need], ['Есть', have], ['К покупке', need], ['Докупить, юани', cost]]);
  for (const row of table.rows) row[3] = {need: row[1], have: row[2]};
  return table;
}
function grade(group,title,route,head,cols,total,extra=[],note='') {
  recipe(group,title,route,[['Стоимость грейда',total],...extra],
    [across(head,cols,[['Нужно',head+1],['Стоимость, юани',head+2]])],note);
}
function standard(group,title,route,head,cols,total,extra=[],note='') {
  recipe(group,title,route,[['Осталось докупить',total],...extra],
    [materials(head,cols,head+1,head+2,head+3)],note);
}
